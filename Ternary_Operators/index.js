//ternary Operators= a shortcut to if{} else{} statements helps to assign
//a variable based on a condition ?

let age=18;
let message=age>=18? "You are allowed to vote": "You are not allowed to vote";
console.log(message);

let time=13;
let message1=time>=12? "Good afternoon":"Good morning";
console.log(message1);

let purchaseamount=120;
let discount=purchaseamount>=100 ? 10:0;
console.log(purchaseamount-discount);